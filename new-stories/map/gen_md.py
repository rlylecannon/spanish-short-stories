w('- **Relatives:** preposition + article + que, con quien, and cuyo (08).')
w('- **Information structure:** clefts (07, 10) and lo + adjective / lo + adjective + que (08).')
w('- **Verbs of change** volverse, hacerse and convertirse (08).')
w('- **Verb phrases:**')
w('  - seguir and acabar + gerund, soler (02);')
