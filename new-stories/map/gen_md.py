#!/usr/bin/env python3
"""Render map.md from map.json (run build_map.py first)."""
import json, os, collections
HERE = os.path.dirname(os.path.abspath(__file__)); BASE = os.path.abspath(os.path.join(HERE, '..', '..'))
m = json.load(open(os.path.join(HERE, 'map.json')))
old = {lv: json.load(open(os.path.join(BASE, f'grammar/{lv}.json'))) for lv in ('b1', 'b2')}
cats = json.load(open(os.path.join(BASE, 'grammar-quiz/categories.json')))
L = []; w = L.append

def table(lv):
    w('| Story | Role | Target topics (status · tokens now → after edits) | Edits | Old topics |')
    w('|---|---|---|---|---|')
    for sid, v in m.items():
        if not sid.startswith(lv): continue
        tps = '<br>'.join(f"**{t['topic']}** ({t['status']} · {t['count_without_edits']}→{t['count']})" for t in v['topics'])
        ne = sum(len(t['edits']) for t in v['topics'])
        ot = '; '.join(x['topic'] for x in old[lv][sid])
        w(f"| {sid} {v['title']} | {v['role']} | {tps} | {ne or '–'} | {ot} |")
    w('')

tot = sum(len(t['edits']) for v in m.values() for t in v['topics'])
ed_st = [s for s, v in m.items() if any(t['edits'] for t in v['topics'])]
w('# B1/B2 grammar map: redesign')
w('')
w('Files: `map.json` (machine-readable), `plan.py` (the source of the map), `build_map.py` (checks every quote and edit against `stories/all-stories.json`, then writes map.json) and `gen_md.py` (writes this page).')
w('')
w('**How to read it:**')
w('- "line N" is the 0-based index into the story\'s `lines` array. Each entry is a paragraph.')
w('- An evidence quote marked `[after edit]` exists only once the proposed edit is applied.')
w('- Every edit replaces text *within* one line, so line counts and plot are unchanged.')
w('- `old` is the exact tag-free substring to replace. `old_raw` and `suggest_es_raw` keep the `<b>` vocab markup; two edits touch a bolded word, and in both the word is kept.')
w('')
w(f'**Totals:** 20 stories, {sum(len(v["topics"]) for v in m.values())} topic slots (31 at B1, 30 at B2), and **{tot} edits in {len(ed_st)} stories** ({", ".join(ed_st)}).')
w('- Every topic now has at least 3 verified tokens.')
w(f'- {sum(1 for v in m.values() for t in v["topics"] if not t["edits"])} of the {sum(len(v["topics"]) for v in m.values())} topic slots need no edit at all.')
w('- No topic string is a headline in more than 2 stories per level.')
w('')
w('## B1 map')
w('')
table('b1')
w('**The B1 progression:**')
w('1. **Consolidation (01–05).** Preterite/imperfect, the present perfect in Madrid (01) and again in Oaxaca (03), and the pluperfect (01, 04 only). Then the future and real si-clauses (02), the conditional (03, 05), relatives with que (03), impersonal se and verb phrases (04), and por/para (05). Reported speech gets a first look in 05.')
w('2. **Subjunctive block (06–08).** Present subjunctive after wish, doubt and importance, linked to negative commands (06). Next comes the full command system with wishes, para que and antes de que (07). Hypothetical si + imperfect subjunctive arrives only after that (08), together with cuando, aunque and ojalá, and donde, lo que and quien relatives.')
w('3. **Extension and recycling (09–10).** Reported commands, ustedes commands and verbs of change (09). Then passive se, subjunctive with hasta que, and por/para recycled (10).')
w('')
w('**What changed against the audit findings:**')
w('- The pluperfect is a headline in 2 stories, down from 8.')
w('- The present perfect is a headline in 2, up from 1, and first appears in the Madrid story.')
w('- si + imperfect subjunctive is a headline in 1 story, down from 3, and now comes after the present subjunctive.')
w('- The past conditional (old b1-05) is no longer a B1 headline.')
w('- The thin topics the audit flagged (b1-04 si-clause, b1-05 hypotheticals, b1-07 speculation and reported commands, b1-09 que + subjunctive, cuando and ojalá) are dropped or moved to stories that support them.')
w('- b1-10 keeps "wishes and hasta que". Its 3+ count rests on the wish tokens, because hasta que itself occurs only once.')
w('')
w('## B2 map')
w('')
table('b2')
w('**The B2 progression:**')
w('1. **Subjunctive consolidation (01–04).** Conjunctions (para que, sin que, hasta que) and aunque, with si + imperfect recycled once (01). Then por mucho que, verb phrases and no es que / temer que (02). Then como si, the ser and se passive, and the imperfect subjunctive after past triggers (03). Then opinion, doubt and emotion, contrast markers, and the pluperfect subjunctive *form* through ojalá and como si (04).')
w('2. **Hypothetical past and reported speech (05–07).** si + pluperfect subjunctive with reported speech (05). estar + participle, reported speech and requests, and time clauses (06). Clefts, with si + pluperfect recycled, and llevar/ir + gerund (07).')
w('3. **Advanced syntax (08–10).** Verbs of change, preposition + relative and cuyo, and lo + adjective (08). Relative subjunctive, discourse markers and conditional of conjecture (09). Reduplicated subjunctive (*diga lo que diga*), clefts and conjecture about the past (10).')
w('')
w('**What changed against the audit findings:**')
w('- si + pluperfect subjunctive is a headline in 2 stories, down from 7.')
w('- Reported speech is a headline in 2, down from 5.')
w('- si + imperfect subjunctive is a headline in 1, down from 3.')
w('- como si is a headline in 1, down from 3.')
w('- Clefts are a headline in 2, down from 3.')
w('- Every area the audit listed as never covered now has a story: para que/sin que/antes de que (01), opinion and doubt (04), cuyo/preposition + relative (08), verbs of change (08), the ser passive (03), lo + adjective (08) and verb phrases (02, 07).')
w('')
w('## Topic families')
w('')
fam = collections.Counter(t['family'] for v in m.values() for t in v['topics'])
w('Every topic uses one of the 15 existing families, apart from **2 proposed new families**:')
w('- **"Por & para"**: b1-05 and b1-10. None of the existing 15 families fits prepositions.')
w('- **"Passive voice"**: b2-03, the ser + participle passive.')
w('')
w('The passive is split on purpose:')
w('- Passive and impersonal *se* stays under "Reflexives & se", as in categories.json today.')
w('- estar + participle goes under "Ser vs. estar".')
w('')
w('Family load: ' + ', '.join(f'{k} {n}' for k, n in fam.most_common()) + '.')
w('')
newstr = sorted({t['topic'] for v in m.values() for t in v['topics'] if t['topic'] not in cats})
w('**Topic strings to add to `grammar-quiz/categories.json`** (string → family):')
seen = set()
for v in m.values():
    for t in v['topics']:
        if t['topic'] not in cats and t['topic'] not in seen:
            seen.add(t['topic']); w(f"- {t['topic']} → {t['family']}")
w('')
dropped = sorted({x['topic'] for lv in old for sid in old[lv] for x in old[lv][sid]} - {t['topic'] for v in m.values() for t in v['topics']})
w('**Old B1/B2 topic strings no longer used as headlines.** Their quiz items and explanations need re-anchoring or retiring. The category keys can stay, since they are harmless:')
w('- ' + '; '.join(dropped))
w('')
w('## By the end of B1 a learner will have met')
w('')
w('This builds on A1/A2: present, ser/estar, gustar, ir a, reflexives, preterite (regular and irregular), imperfect, estar + gerund, tú commands, object and double pronouns, comparatives, and a first look at he/había + participle in a2-09/10.')
w('- **Past narration:**')
w('  - preterite vs. imperfect (01);')
w('  - present perfect vs. preterite, including Peninsular vs. American use (01, 03);')
w('  - pluperfect (01, 04).')
w('- **Future and conditional:**')
w('  - simple future (02);')
w('  - future in the past (01);')
w('  - conditional for advice and hypotheses (03, 05).')
w('- **Conditions:**')
w('  - real si + present (02, with plenty more recycling in b1-10);')
w('  - hypothetical si + imperfect subjunctive + conditional (08).')
w('- **Present subjunctive:**')
w('  - wishes (querer/esperar que), importance and doubt with no creo que (06, 07, 10);')
w('  - purpose and time with para que and antes de que (07);')
w('  - cuando, aunque and ojalá (08);')
w('  - hasta que (10).')
w('- **Commands:**')
w('  - negative tú commands (06);')
w('  - the full tú/usted/ustedes system with attached pronouns (07, 09).')
w('- **Reported speech:**')
w('  - statements with backshift (05, 06);')
w('  - reported commands with que + imperfect subjunctive (09, for recognition).')
w('- **se:** impersonal (04) and passive (10).')
w('- **Relatives:** que and en que, defining and non-defining (03); donde, lo que and quien (08).')
w('- **Other:**')
w('  - object pronoun order se lo / te la (02);')
w('  - verb phrases llevar + gerund, seguir and volver a (04);')
w('  - por vs. para (05, 10);')
w('  - verbs of change ponerse, quedarse and convertirse (09).')
w('')
w('**Compared with the Plan Curricular B1 grammar inventory (Instituto Cervantes; summarised, so check the exact section numbers before quoting):**')
w('- **Covered:** pretérito perfecto/indefinido/imperfecto/pluscuamperfecto contrasts; futuro simple; condicional simple; imperativo afirmativo and negativo with pronouns; presente de subjuntivo in sustantivas (deseo, duda, valoración) and adverbiales (finales, temporales, concesivas con aunque); condicionales reales and irreales (si + imperfecto de subjuntivo); estilo indirecto with tense shifts; se impersonal and pasiva refleja; relativos que/donde/quien/lo que; por/para; pronombres combinados; perífrasis (llevar + gerundio, seguir + gerundio, volver a); verbos de cambio ponerse/quedarse.')
w('- **Not covered:**')
w('  - *pretérito perfecto de subjuntivo* (haya + participle) has **0 tokens in all 20 B1/B2 stories**. It is the largest gap at both levels.')
w('  - futuro perfecto (habrá + participle) also has 0 tokens.')
w('  - acabar de and dejar de have 0 and 1 tokens respectively (b1-06, dejé de preguntar).')
w('  - *lo + adjective* (lo bueno es que…) is often listed at B1 but here is first a headline at b2-08.')
w('  - ser vs. estar with adjectives that change meaning is not a headline anywhere at B1/B2 any more.')
w('')
w('## By the end of B2 a learner will have met')
w('')
w('Everything above, plus:')
w('- **Imperfect subjunctive:**')
w('  - after past triggers (03);')
w('  - como si (03);')
w('  - concessives with aunque, por mucho que and por + adjective + que (01, 02);')
w('  - no es que, temer que and a que (02);')
