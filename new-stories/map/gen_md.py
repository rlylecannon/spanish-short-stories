w('  - time clauses with cuando, hasta que and mientras in past narrative (06);')
w('  - relative clauses with an unknown or non-existent antecedent (09);')
w('  - reduplicated forms such as diga lo que diga and fuera quien fuera (10).')
w('- **Pluperfect subjunctive and conditional perfect:** ojalá and como si (04), si-clauses (05, 07) and aunque (05).')
