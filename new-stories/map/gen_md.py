w('')
w('**Compared with the Plan Curricular B2 inventory (summarised):**')
w('- **Covered:** pluscuamperfecto de subjuntivo; condicional compuesto (hypothesis and probability); oraciones concesivas (aunque + subjuntivo, por mucho que); finales and temporales with subjuntivo; subjuntivo with verbs of opinion; relativas with preposition and cuyo; voz pasiva con ser and estar + participio; verbos de cambio; perífrasis; estructuras enfáticas (relieve: fue … quien); conectores discursivos.')
w('- **Not covered:**')
