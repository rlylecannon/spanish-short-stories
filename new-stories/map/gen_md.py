w('  - Covered: Por vs. para (05, 10); Present perfect vs. preterite (01, 03); Object pronoun order (02); Passive and impersonal se (04, 10).')
w('  - Partly covered: *Subjunctive after para que, antes de que, sin que*. para que and antes de que are in 07, but **sin que** is not at B1; it is first a headline at b2-01. *Verb phrases: llevar + gerund, acabar de, volver a, dejar de*. llevar and volver a are in 04, but **acabar de** (0 tokens anywhere) and **dejar de** (1 token, b1-06) are uncovered.')
w('- **essentials-b2:** all 6 topics are now covered by stories.')
w('  - conjunctions (01);')
